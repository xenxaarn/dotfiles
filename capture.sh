#!/usr/bin/env bash
set -euo pipefail
T="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/Tokyo-Night"
X="${XDG_CONFIG_HOME:-$HOME/.config}/xfce4/xfconf/xfce-perchannel-xml"
D="$T/.config/xfce4/xfconf/xfce-perchannel-xml"
mkdir -p "$D"
for c in xsettings xfwm4 xfce4-panel; do cp -v "$X/$c.xml" "$D/"; done
dconf dump /net/launchpad/plank/docks/dock1/ | sed 's|^\[/\]|[net/launchpad/plank/docks/dock1]|' >"$T/dconf/10-plank"
cat "$T/dconf/10-plank"
echo "Plank launchers are generated by install.sh (mk_item); edit them there."
